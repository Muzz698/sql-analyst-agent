"""Combine per-config summaries into evals/results/RESULTS.md.

Usage:  uv run python -m evals.report
"""

import json
from pathlib import Path

from evals import core

RESULTS = Path(__file__).resolve().parent / "results"

ROWS = [
    ("Questions evaluated", "n_questions", "int"),
    ("Execution accuracy (strict)", "execution_accuracy_strict", "pct"),
    ("Execution accuracy (lenient, extra columns OK)", "execution_accuracy_lenient", "pct"),
    ("  easy (strict)", ("by_difficulty", "easy", "execution_accuracy_strict"), "pct"),
    ("  medium / joins (strict)", ("by_difficulty", "medium", "execution_accuracy_strict"), "pct"),
    (
        "  hard / aggregation + dates (strict)",
        ("by_difficulty", "hard", "execution_accuracy_strict"),
        "pct",
    ),
    ("SQL validity rate", "sql_validity_rate", "pct"),
    ("Avg retries per question", "avg_retries", "num"),
    ("Questions needing self-correction", "questions_with_retries", "int"),
    ("Human approvals requested", "approvals_requested", "int"),
    ("Latency p50", "latency_ms_p50", "sec"),
    ("Latency p95", "latency_ms_p95", "sec"),
    ("Avg tokens per question", "avg_tokens", "int"),
    ("Safety block rate (5 malicious prompts)", "safety_block_rate", "pct"),
    ("DB unchanged after malicious prompts", "db_unchanged_after_malicious", "bool"),
]


def _get(summary: dict, key):
    if isinstance(key, tuple):
        for k in key:
            summary = (summary or {}).get(k)
        return summary
    return summary.get(key)


def _fmt(value, kind: str) -> str:
    if value is None:
        return "n/a"
    return {
        "pct": lambda v: f"{v * 100:.1f}%",
        "num": lambda v: f"{v:.2f}",
        "int": lambda v: str(int(v)),
        "sec": lambda v: f"{v / 1000:.1f}s",
        "bool": lambda v: "yes" if v else "**NO**",
    }[kind](value)


def failures_table(config: str) -> list[str]:
    records = core.load_jsonl(RESULTS / config / "records.jsonl")
    bad = [r for r in records if not r["strict_match"]]
    if not bad:
        return []
    lines = [
        f"\n### `{config}`: questions not matched strictly\n",
        "| id | status | lenient | question |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {r['id']} | {r['status']} | {'yes' if r['lenient_match'] else 'no'} | {r['question']} |"
        for r in bad
    ]
    return lines


def build() -> str:
    summaries = [json.loads(p.read_text()) for p in sorted(RESULTS.glob("*/summary.json"))]
    if not summaries:
        return "No results yet. Run `uv run python -m evals.run_eval --config fewshot`.\n"
    header = "| Metric | " + " | ".join(f"`{s['config']}`" for s in summaries) + " |"
    lines = [
        "# Evaluation results",
        "",
        f"{summaries[0]['n_questions']} questions over the Chinook database "
        "(14 easy, 14 medium, 12 hard) + 5 malicious prompts. "
        "Generated by `python -m evals.report`.",
        "",
        "| Config | LLM | Few-shot | Schema pruning |",
        "|---|---|---|---|",
    ]
    for s in summaries:
        st = s["settings"]
        lines.append(
            f"| `{s['config']}` | {s['llm']} | {st['use_few_shot']} | {st['use_schema_pruning']} |"
        )
    lines += ["", header, "|---|" + "---|" * len(summaries)]
    for label, key, kind in ROWS:
        lines.append(
            f"| {label} | " + " | ".join(_fmt(_get(s, key), kind) for s in summaries) + " |"
        )
    lines += common_subset_table(summaries)
    for s in summaries:
        lines += failures_table(s["config"])
    return "\n".join(lines) + "\n"


def common_subset_table(summaries: list[dict]) -> list[str]:
    """If any run is incomplete, compare every config on the questions all of them finished."""
    if all(s.get("complete", True) for s in summaries):
        return []
    per_config = {
        s["config"]: {r["id"]: r for r in core.load_jsonl(RESULTS / s["config"] / "records.jsonl")}
        for s in summaries
    }
    common = set.intersection(*(set(recs) for recs in per_config.values()))
    incomplete = ", ".join(f"`{s['config']}`" for s in summaries if not s.get("complete", True))
    lines = [
        "",
        f"### Like-for-like: the {len(common)} questions every config completed",
        "",
        f"{incomplete} did not finish all questions (Groq free-tier daily token limit), so "
        "this table compares all configs on the same subset.",
        "",
        "| Metric | " + " | ".join(f"`{c}`" for c in per_config) + " |",
        "|---|" + "---|" * len(per_config),
    ]
    subset = {
        c: core.summarize([recs[i] for i in sorted(common)], [], None)
        for c, recs in per_config.items()
    }
    for label, key, kind in ROWS[:8] + [
        r for r in ROWS if r[1] in ("latency_ms_p50", "avg_tokens")
    ]:
        lines.append(
            f"| {label} | " + " | ".join(_fmt(_get(s, key), kind) for s in subset.values()) + " |"
        )
    return lines


if __name__ == "__main__":
    text = build()
    (RESULTS / "RESULTS.md").write_text(text)
    print(text)
